// Cálculo del precio según el GRL: cuanto más alto GRL, mayor valor
export function getPlayerPrice(grl: number): number {
  if (grl >= 130) return 600;
  if (grl >= 129) return 550;
  if (grl >= 128) return 500;
  if (grl >= 127) return 450;
  if (grl >= 126) return 400;
  if (grl >= 125) return 350;
  if (grl >= 124) return 300;
  if (grl >= 122) return 250;
  if (grl >= 120) return 200;
  if (grl >= 115) return 150;
  return 100;
}

// Helper to find player by ID
export function getPlayerById(id: string): PlayerData | undefined {
  return WORLD_CUP_PLAYERS.find((p) => p.id === id);
}

// Helper to filter players
export function filterPlayers(position?: string, search?: string): PlayerData[] {
  return WORLD_CUP_PLAYERS.filter((p) => {
    const matchesPos = !position || position === 'TODOS' || p.position === position;
    const matchesSearch =
      !search ||
      p.name.toLowerCase().includes(search.toLowerCase()) ||
      p.shortName.toLowerCase().includes(search.toLowerCase()) ||
      p.country.toLowerCase().includes(search.toLowerCase());
    return matchesPos && matchesSearch;
  });
}
